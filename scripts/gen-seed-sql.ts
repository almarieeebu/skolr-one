// Turns lib/data/seed.ts into supabase/seed.sql so demo mode and the real
// database start with the same data. Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import path from "node:path";
import * as seed from "../lib/data/seed";

type Row = Record<string, unknown>;

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) {
    // text[] columns
    return `array[${v.map((x) => lit(String(x))).join(", ")}]::text[]`;
  }
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Row[]): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const jsonCols = new Set([
    "overrides", "settings", "misc_items", "exam_periods", "plans",
    "period_weights", "college_scale", "k12_weights", "deadlines", "scores", "domains", "old_value", "new_value",
  ]);
  const cell = (c: string, v: unknown) => (jsonCols.has(c) ? `${lit(JSON.stringify(v))}::jsonb` : lit(v));
  const values = rows.map((r) => `  (${cols.map((c) => cell(c, r[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${cols.join(", ")}) values\n${values};\n\n`;
}

let sql = `-- GENERATED by scripts/gen-seed-sql.ts from lib/data/seed.ts. Do not edit by hand.
-- Sample Academy (SA): demo logins all use the password '${seed.DEMO_PASSWORD}'.

`;

// Auth users (works on local Supabase and in the hosted SQL editor).
for (const p of seed.profiles) {
  sql += `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', ${lit(p.id)}, 'authenticated', 'authenticated', ${lit(p.email)},
  crypt(${lit(seed.DEMO_PASSWORD)}, gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', ${lit(JSON.stringify({ full_name: p.full_name }))}, now(), now(), '', '', '', '')
on conflict (id) do nothing;
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${lit(p.id)}, ${lit(p.id)},
  ${lit(JSON.stringify({ sub: p.id, email: p.email, email_verified: true }))}::jsonb, 'email', now(), now(), now())
on conflict do nothing;

`;
}

const profileRows = seed.profiles.map((p) => ({ ...p }));
sql += insert("profiles", profileRows).replace(/;\n\n$/, "\non conflict (id) do update set full_name = excluded.full_name, email = excluded.email;\n\n");
sql += insert("schools", [seed.school as unknown as Row]);
sql += insert("branches", seed.branches);
sql += insert("memberships", seed.memberships as unknown as Row[]);
sql += insert("terms", seed.terms as unknown as Row[]);
sql += insert("students", seed.students as unknown as Row[]);
sql += insert("parent_links", seed.parentLinks as unknown as Row[]);
sql += insert("offerings", seed.offerings as unknown as Row[]);
sql += insert("enrollments", seed.enrollments as unknown as Row[]);
sql += insert("documents", seed.documents as unknown as Row[]);
sql += insert("enrollment_loads", seed.enrollmentLoads as unknown as Row[]);
sql += insert("fee_setups", seed.feeSetups as unknown as Row[]);
sql += insert("discounts", seed.discounts as unknown as Row[]);
sql += insert("payments", seed.payments as unknown as Row[]);
// Ledger rows in posting order (seq follows insert order).
sql += insert("ledger_entries", seed.ledger as unknown as Row[]);
sql += insert("or_series", [seed.orSeries as unknown as Row]);
sql += insert("enrollment_history", seed.history as unknown as Row[]);

// Grades. Posted sheets are seeded as they are, so the guard trigger is told
// this is an internal write; the entry trigger still works out each grade.
sql += `select set_config('grades.internal', 'on', false);\n\n`;
sql += insert("grade_settings", [seed.gradeSettings as unknown as Row]).replace(
  /;\n\n$/,
  "\non conflict (school_id) do update set college_average = excluded.college_average, period_weights = excluded.period_weights,\n" +
    "  block_average_on_inc = excluded.block_average_on_inc, gwa_decimals = excluded.gwa_decimals, passing_grade = excluded.passing_grade,\n" +
    "  college_scale = excluded.college_scale, k12_weights = excluded.k12_weights, deadlines = excluded.deadlines, updated_at = excluded.updated_at;\n\n",
);
sql += insert("grade_sheets", seed.gradeSheets as unknown as Row[]);
sql += insert("k12_score_items", seed.scoreItems as unknown as Row[]);
sql += insert("grade_entries", seed.gradeEntries as unknown as Row[]);
sql += insert("change_grade_requests", seed.changeRequests as unknown as Row[]);
sql += insert("grade_history", seed.gradeHistory as unknown as Row[]);
sql += `select set_config('grades.internal', '', false);\n`;

const out = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
